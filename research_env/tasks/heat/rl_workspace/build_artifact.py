"""Package a model.py-style module into artifact/ by fitting it on the training manifest.

Usage (from the workspace root):
    python tools/build_artifact.py baselines/ridge_lag.py [--seed 0] [--out artifact]

The module must define ``train(train_manifest, calibration_manifest, output_dir, seed)``
and ``predict(artifact_dir, request)``. The artifact gets a copy of the module
(as ``model.py``), ``heatlib.py`` and a small ``inference.py`` entry point.
"""
import argparse
import hashlib
import importlib.util
import json
import shutil
import sys
from pathlib import Path

INFERENCE = '''"""Generated by tools/build_artifact.py."""
import sys
from pathlib import Path

_here = Path(__file__).resolve().parent
if str(_here) not in sys.path:
    sys.path.insert(0, str(_here))
import model as _model


def predict(artifact_dir, request):
    return _model.predict(artifact_dir, request)
'''


def _sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def build(model_py, out="artifact", train="data/train_manifest.json", seed=0, heatlib="heatlib.py"):
    model_py, out, heatlib = Path(model_py).resolve(), Path(out), Path(heatlib).resolve()
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    shutil.copyfile(model_py, out / "model.py")
    local = model_py.parent / "heatlib.py"
    shutil.copyfile(local if local.is_file() else heatlib, out / "heatlib.py")
    sys.path.insert(0, str(out.resolve()))
    try:
        spec = importlib.util.spec_from_file_location("model", out / "model.py")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        result = module.train(str(train), None, str(out), int(seed))
    finally:
        sys.path.remove(str(out.resolve()))
    (out / "inference.py").write_text(INFERENCE)
    (out / "build.json").write_text(json.dumps({
        "model_sha256": _sha(out / "model.py"), "train_manifest_sha256": _sha(train),
        "seed": int(seed), "train_result": result if isinstance(result, dict) else {}},
        indent=1, sort_keys=True, allow_nan=False))
    return out


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("model_py")
    ap.add_argument("--out", default="artifact")
    ap.add_argument("--train", default="data/train_manifest.json")
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    print(build(a.model_py, a.out, a.train, a.seed))
